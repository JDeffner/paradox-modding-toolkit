export type IconName = keyof typeof PATHS;

/** Every icon name, for a page that ships the whole set to an inline script. */
export const ICON_NAMES = Object.keys(PATHS) as IconName[];

export function icon(name: IconName, className = "px-icon"): string {
  return `<svg class="${className}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${PATHS[name]}</svg>`;
}

/** The same icon as a DOM node, for code that builds its tree with createElement. */
export function iconEl(name: IconName, className = "px-icon"): SVGSVGElement {
  const t = document.createElement("template");
  t.innerHTML = icon(name, className);
  return t.content.firstElementChild as SVGSVGElement;
}
